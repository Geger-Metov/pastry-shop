from decimal import Decimal

# Деньги всегда Decimal (в БД numeric(10, 2)), никогда float: 0.1 + 0.2 != 0.3.
# Тип - только сумма. Валюта хранится один раз на заказ (Order.currency, ISO 4217) и берётся
# из настроек магазина: суммы позиций, доставки и платежей заказа - в валюте заказа.
# Язык интерфейса (Locale) на валюту не влияет: смена языка не должна менять цены.
type Money = Decimal
